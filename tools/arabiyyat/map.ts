/**
 * Builds the عربيّات mini map (src/pages/arabiyyat/ui/mapData.ts) from Natural Earth's 1:50m land
 * polygons (public domain, https://www.naturalearthdata.com/). Coastlines only, no borders: the map
 * just shows where a book's place is, and never draws a frontier.
 *
 *   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_50m_land.geojson
 *   npx tsx tools/arabiyyat/map.ts ne_50m_land.geojson
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { BOUNDS, WIDTH, project } from "../../src/pages/arabiyyat/ui/projection";

type Pt = [number, number];

/** Clip a few degrees outside the visible bounds, so the cut edges (which would be stroked like a
 * coastline) fall outside the SVG's viewBox and only real coast shows. */
const PAD = 3;
const CLIP = { west: BOUNDS.west - PAD, east: BOUNDS.east + PAD, south: BOUNDS.south - PAD, north: BOUNDS.north + PAD };

/** Sutherland–Hodgman: clip a ring (lon/lat) to CLIP. */
function clip(ring: Pt[]): Pt[] {
  const edges: [(p: Pt) => boolean, (a: Pt, b: Pt) => Pt][] = [
    [(p) => p[0] >= CLIP.west, (a, b) => at(a, b, 0, CLIP.west)],
    [(p) => p[0] <= CLIP.east, (a, b) => at(a, b, 0, CLIP.east)],
    [(p) => p[1] >= CLIP.south, (a, b) => at(a, b, 1, CLIP.south)],
    [(p) => p[1] <= CLIP.north, (a, b) => at(a, b, 1, CLIP.north)],
  ];
  let out = ring;
  for (const [inside, cross] of edges) {
    const input = out;
    out = [];
    for (let i = 0; i < input.length; i++) {
      const cur = input[i];
      const prev = input[(i + input.length - 1) % input.length];
      if (inside(cur)) {
        if (!inside(prev)) out.push(cross(prev, cur));
        out.push(cur);
      } else if (inside(prev)) out.push(cross(prev, cur));
    }
    if (!out.length) break;
  }
  return out;
}

function at(a: Pt, b: Pt, axis: 0 | 1, value: number): Pt {
  const t = (value - a[axis]) / (b[axis] - a[axis]);
  return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
}

/** Douglas–Peucker on projected points. */
function simplify(pts: Pt[], tol: number): Pt[] {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack: [number, number][] = [[0, pts.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop()!;
    let max = 0;
    let idx = -1;
    const [x1, y1] = pts[s];
    const [x2, y2] = pts[e];
    const len = Math.hypot(x2 - x1, y2 - y1) || 1;
    for (let i = s + 1; i < e; i++) {
      const d = Math.abs((y2 - y1) * pts[i][0] - (x2 - x1) * pts[i][1] + x2 * y1 - y2 * x1) / len;
      if (d > max) [max, idx] = [d, i];
    }
    if (max > tol && idx > 0) {
      keep[idx] = 1;
      stack.push([s, idx], [idx, e]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

const file = process.argv[2];
if (!file) throw new Error("usage: tsx tools/arabiyyat/map.ts ne_50m_land.geojson");
const geo = JSON.parse(readFileSync(file, "utf8")) as { features: { geometry: { type: string; coordinates: unknown } }[] };
const rings: Pt[][] = geo.features.flatMap((f) =>
  f.geometry.type === "Polygon"
    ? [(f.geometry.coordinates as Pt[][])[0]]
    : (f.geometry.coordinates as Pt[][][]).map((poly) => poly[0]),
);

const paths: string[] = [];
for (const ring of rings) {
  const clipped = clip(ring);
  if (clipped.length < 3) continue;
  const pts = simplify(
    clipped.map(([lon, lat]) => project(lat, lon)),
    0.6,
  );
  // Skip specks (small islands) that would only add noise at this size.
  const xs = pts.map((p) => p[0]);
  const ys = pts.map((p) => p[1]);
  if (pts.length < 4 || Math.max(...xs) - Math.min(...xs) + Math.max(...ys) - Math.min(...ys) < 4) continue;
  paths.push("M" + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join("L") + "Z");
}

const out = resolve(import.meta.dirname, "../../src/pages/arabiyyat/ui/mapData.ts");
writeFileSync(
  out,
  `// Generated by tools/arabiyyat/map.ts from Natural Earth 1:50m land (public domain). Do not edit.\n` +
    `// Coastlines only, ${WIDTH} wide; see projection.ts for the bounds.\n` +
    `export const LAND = ${JSON.stringify(paths.join(""))};\n`,
);
console.log(`${out}: ${paths.length} shapes, ${(paths.join("").length / 1024).toFixed(1)} KB`);
