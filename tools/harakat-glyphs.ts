/**
 * Extracts the haraka (diacritic) outlines from the Amiri font into SVG path data, so the game's
 * keyboard can draw each mark large over a dotted circle (like Android's Arabic keyboard) without
 * depending on font fallback or a ◌ glyph (Amiri has none).
 *
 *   npm run harakat-glyphs   → writes src/pages/shakkil/ui/harakatGlyphs.ts (committed)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import opentype from "opentype.js";
import { woffToSfnt } from "./og";

const ROOT = resolve(import.meta.dirname, "..");
const WOFF = resolve(ROOT, "node_modules/@fontsource/amiri/files/amiri-arabic-400-normal.woff");
const OUT = resolve(ROOT, "src/pages/shakkil/ui/harakatGlyphs.ts");

const MARKS = {
  a: "َ",
  u: "ُ",
  i: "ِ",
  o: "ْ",
  an: "ً",
  un: "ٌ",
  in: "ٍ",
  shadda: "ّ",
} as const;

const sfnt = woffToSfnt(readFileSync(WOFF));
const font = opentype.parse(sfnt.buffer.slice(sfnt.byteOffset, sfnt.byteOffset + sfnt.byteLength));
const SIZE = 1000; // draw at 1000 units so coordinates are plain numbers

const glyphs = Object.fromEntries(
  Object.entries(MARKS).map(([name, ch]) => {
    const glyph = font.charToGlyph(ch);
    if (!glyph || glyph.index === 0) throw new Error(`Amiri has no glyph for ${name}`);
    const path = glyph.getPath(0, 0, SIZE);
    const box = path.getBoundingBox();
    return [
      name,
      {
        d: path.toPathData(1),
        // Bounding box in the same coordinate space (y grows downwards, baseline at 0).
        box: [box.x1, box.y1, box.x2, box.y2].map((v) => Math.round(v * 10) / 10),
      },
    ];
  }),
);

writeFileSync(
  OUT,
  `// Generated by tools/harakat-glyphs.ts from the Amiri font (SIL Open Font License). Do not edit.
// Path data at 1000 units per em; box = [x1, y1, x2, y2] with y growing downwards from the baseline.
export const HARAKAT_GLYPHS = ${JSON.stringify(glyphs, null, 2)} as const;

export type HarakaGlyphName = keyof typeof HARAKAT_GLYPHS;
`,
  "utf8",
);
console.log(`wrote ${OUT}`);
for (const [k, g] of Object.entries(glyphs)) console.log(k.padEnd(7), g.box.join(" "), `${g.d.length} chars`);
console.log("has U+25CC:", font.charToGlyph("◌").index !== 0);
